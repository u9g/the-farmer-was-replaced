def fmc(B, T):
	n = 0
	while n < 16:
		v = measure()
		bd = None
		bv = v
		for d in B:
			w = measure(d)
			while w == None:
				w = measure(d)
			if w > bv:
				bv = w
				bd = d
		if bd != None:
			swap(bd)
			n += 1
		else:
			td = None
			tv = v
			for d in T:
				w = measure(d)
				while w == None:
					w = measure(d)
				if w < tv:
					tv = w
					td = d
			if td != None:
				swap(td)
				n += 1
			else:
				return n
	return n


